#!/usr/bin/env python3
"""Generates the SDK tables that are defined by a formula, as MWCC inline-asm `dcd`/`dcb` lines.

main keeps its read-only data inside .text, so the table files under libs/ emit their tables from
`asm` blocks of `dcd` words (which give the objects the `$d` mapping symbol objdiff needs). The bodies of the
formula tables are written here at build time and pulled in with #include:

  fx_sincos.inc    FX_SinCosTable_[4096][2]: (sin, cos) of 2*pi*i/4096 in fx16 (1.0 = 4096)
  fx_atan.inc      FX_AtanTable_[129]: atan(i/128) in the 65536-per-turn angle unit
  snd_decibel.inc  SNDi_DecibelTable[128]: 20*log10(i/127) in 0.1 dB, with -32768 for silence

Usage: gen_tables.py OUTDIR
"""

import math
import sys
from pathlib import Path


def round_half_away(x: float) -> int:
    return int(math.floor(abs(x) + 0.5)) * (1 if x >= 0 else -1)


def halfwords_to_asm(values: list[int]) -> str:
    out = []
    for i in range(0, len(values) - 1, 2):
        lo = values[i] & 0xffff
        hi = values[i + 1] & 0xffff
        out.append(f"    dcd 0x{hi << 16 | lo:08x}\n")
    if len(values) % 2:
        # The last entry with the zero padding to the next word: a `dcb` would switch the
        # assembler's mapping symbol back to `$a`.
        out.append(f"    dcd 0x{values[-1] & 0xffff:08x}\n")
    return "".join(out)


def sincos() -> list[int]:
    values = []
    for i in range(4096):
        a = 2.0 * math.pi * i / 4096
        values.append(round_half_away(math.sin(a) * 4096))
        values.append(round_half_away(math.cos(a) * 4096))
    return values


def atan() -> list[int]:
    return [round_half_away(math.atan(i / 128) * 32768 / math.pi) for i in range(129)]


def decibel() -> list[int]:
    return [-32768] + [round_half_away(200 * math.log10(i / 127)) for i in range(1, 128)]


TABLES = {
    "fx_sincos.inc": sincos,
    "fx_atan.inc": atan,
    "snd_decibel.inc": decibel,
}


def main():
    out_dir = Path(sys.argv[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, fn in TABLES.items():
        text = "// Generated by tools/gen_tables.py. Do not edit.\n" + halfwords_to_asm(fn())
        (out_dir / name).write_text(text)


if __name__ == "__main__":
    main()
